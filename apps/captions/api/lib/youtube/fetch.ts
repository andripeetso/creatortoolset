/**
 * YouTube video info through Apify (the same account token as Instagram).
 * One run per link: the actor's item becomes the raw info we store, and its
 * SRT (inline, or the srtUrl it links) is kept on the item so re-reading the
 * stored raw later gives the same transcript.
 */
import { apifyRun, type ApifyFetchOptions } from "../instagram/apify";
import type { PostInfo } from "../instagram/types";
import { InstagramError } from "../instagram/web-api";
import { normalizeYoutubeItem, pickSrt } from "./normalize";
import type { YoutubeRef } from "./url";

type Rec = Record<string, unknown>;

/** Actor docs: https://apify.com/streamers/youtube-scraper (input and output checked 2026-11-05). */
export const YOUTUBE_ACTOR = "streamers~youtube-scraper";

/**
 * The docs name the subtitle option only as an example value ("NONE" is the
 * example). "SUBTITLES" is the guess for the free option; check it on the first
 * live run with a real token (the actor rejects unknown values).
 */
export function youtubeActorInput(url: string): Rec {
  return {
    startUrls: [{ url }],
    maxResults: 1,
    maxResultsShorts: 1,
    maxResultStreams: 0,
    transcriptionAndSubtitle: "SUBTITLES",
    subtitlesLanguage: "en",
    subtitlesFormat: "srt",
    preferAutoGeneratedSubtitles: true,
  };
}

const SRT_MAX_CHARS = 5 * 1024 * 1024;

async function fillSrtFromUrl(item: Rec, opts: ApifyFetchOptions): Promise<void> {
  if (pickSrt(item)) return;
  const subs = Array.isArray(item.subtitles) ? (item.subtitles as Rec[]) : [];
  const withUrl = subs.find((s) => typeof s.srtUrl === "string");
  if (!withUrl) return;
  try {
    const res = await (opts.fetchImpl ?? fetch)(withUrl.srtUrl as string, {
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) return;
    const text = await res.text();
    if (text.length <= SRT_MAX_CHARS) withUrl.srt = text;
  } catch {
    // No captions is a normal outcome; the post says so.
  }
}

export async function fetchYoutubeViaApify(
  ref: YoutubeRef,
  opts: ApifyFetchOptions,
): Promise<{ raw: Rec; info: PostInfo }> {
  const items = (await apifyRun(YOUTUBE_ACTOR, youtubeActorInput(ref.canonical), opts)).filter(
    (i): i is Rec => !!i && typeof i === "object",
  );
  const good = items.filter((i) => !i.error);
  const item = good.find((i) => i.id === ref.videoId) ?? good[0];
  if (!item) {
    const bad = items.find((i) => i.error);
    const why = bad ? String(bad.note ?? bad.error) : "YouTube returned no video for this link";
    throw new InstagramError(why, "NOT_FOUND", false);
  }
  await fillSrtFromUrl(item, opts);
  return { raw: item, info: normalizeYoutubeItem(item, ref) };
}
